const round2 = (n: number) => Math.round(n * 100) / 100;

function findPrice(rows: readonly RateRow[], weight: number): number | null {
  for (const [min, max, price] of rows) {
    if (weight >= min && weight < max) return price;
  }
  // Band upper bounds are exclusive, so a parcel sitting exactly on the top of
  // the table (150 lb ground) would otherwise fall through — quote it there.
  const last = rows[rows.length - 1];
  return weight === last[1] ? last[2] : null;
}

export type ServiceQuote = {
  service: ShippingService;
  /** Published carrier rate before our negotiated discount. */
  listPrice: number;
  /** What the customer pays. */
  price: number;
};

export type QuoteResult =
  | {
      status: "ok";
      destination: Destination;
      quotes: ServiceQuote[];
      /** Plain-language reasons a service is missing from the list. */
      notices: string[];
    }
  | { status: "over-limit"; destination: Destination; limit: number };

/** Price a single service, or null when it isn't rated for this shipment. */
export function quoteService(
  serviceId: ServiceId,
  weight: number,
  destination: Destination,
): ServiceQuote | null {
  const service = shippingServices.find((s) => s.id === serviceId);
  if (!service) return null;

  const table = RATE_TABLES[serviceId];
  const rows =
    destination.kind === "territory"
      ? table.territory
      : table.domestic[destination.zone <= 4 ? "1-4" : "4-8"];
  if (!rows) return null;

  const listPrice = findPrice(rows, weight);
  if (listPrice === null) return null;

  return {
    service,
    listPrice,
    price: round2(listPrice * (1 - service.discount / 100)),
  };
}

/**
 * Price every service available for a shipment.
 *
 * Availability rules:
 * - AK/HI/PR cap at 30 lb and never move by ground.
 * - Under 1 lb, ground doesn't run — the parcel goes by mail or air.
 * - Over 30 lb, the air services drop out and ground carries it up to 150 lb.
 */
export function quoteShipment(
  destination: Destination,
  weight: number,
): QuoteResult {
  const isTerritory = destination.kind === "territory";
  const limit = isTerritory ? WEIGHT_LIMITS.territory : WEIGHT_LIMITS.domestic;

  if (weight > limit) return { status: "over-limit", destination, limit };

  const notices: string[] = [];
  let available = shippingServices;

  if (isTerritory) {
    available = available.filter((s) => s.id !== "ground");
    notices.push(
      `Ground service isn't available for ${destination.label} — air and mail only.`,
    );
  } else if (weight > AIR_MAX_WEIGHT) {
    available = available.filter((s) => s.id === "ground");
    notices.push(
      `Over ${AIR_MAX_WEIGHT} lb, ground is the only service we quote online. Ask us about freight.`,
    );
  } else if (weight < GROUND_MIN_WEIGHT) {
    available = available.filter((s) => s.id !== "ground");
    notices.push(`Ground service starts at ${GROUND_MIN_WEIGHT} lb.`);
  }

  const quotes = available
    .map((s) => quoteService(s.id, weight, destination))
    .filter((q): q is ServiceQuote => q !== null);

  return { status: "ok", destination, quotes, notices };
}

/** Format a rate for display, e.g. `$27.59`. */
export function formatPrice(value: number): string {
  return value.toLocaleString("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
}
