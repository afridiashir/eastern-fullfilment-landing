export type TerritoryCode = "AK" | "HI" | "PR";

const TERRITORY_PREFIXES: Record<
  TerritoryCode,
  { name: string; ranges: readonly PrefixRange[] }
> = {
  AK: { name: "Alaska", ranges: [[995, 999]] },
  HI: { name: "Hawaii", ranges: [[967, 968]] },
  PR: { name: "Puerto Rico", ranges: [[6, 7], [9, 9]] },
};

export type Destination =
  | { kind: "domestic"; zone: number; label: string }
  | { kind: "territory"; code: TerritoryCode; label: string };

const inRanges = (prefix: number, ranges: readonly PrefixRange[]) =>
  ranges.some(([from, to]) => prefix >= from && prefix <= to);

export const isValidZip = (zip: string) => /^\d{5}$/.test(zip);

/** Resolve a 5-digit ZIP to its zone or territory. Returns null for bad input. */
export function getDestination(zip: string): Destination | null {
  if (!isValidZip(zip)) return null;
  const prefix = Number(zip.slice(0, 3));

  for (const code of Object.keys(TERRITORY_PREFIXES) as TerritoryCode[]) {
    if (inRanges(prefix, TERRITORY_PREFIXES[code].ranges)) {
      return { kind: "territory", code, label: TERRITORY_PREFIXES[code].name };
    }
  }

  const match = ZONE_PREFIXES.find((z) => inRanges(prefix, z.ranges));
  const zone = match?.zone ?? 8;
  return { kind: "domestic", zone, label: `Zone ${zone}` };
}

